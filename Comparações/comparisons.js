// Comparações
    // maior e menor: > e <
    // maior ou igual e menor ou igual: >= e <=
    // igual: ==
    // diferente: !=
    // idêntico: ===

// exemplos:
    console.log(4 <= 4)
    console.log(10 == 10)
    console.log(10 === "10")
    console.log(5 != 5)
    console.log(5 != "5")
    console.log(5 !== "5")