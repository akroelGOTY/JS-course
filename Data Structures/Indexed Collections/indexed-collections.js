// 📦 Indexed Collections são estruturas onde os valores são acessados por índice numérico.
    // Exemplo: Array (lista) -> 👉 guarda vários valores em ordem
    const numeros = [10, 20, 30];

    // Acessando valores por índice
    console.log(numeros[0]); // 10
    console.log(numeros[1]); // 20
    console.log(numeros[2]); // 30

    // 🧠 Diferença mental importante
        // 📦 Indexed Collections
        //  → organizadas por posição (0, 1, 2, 3…)

    // 🚀 Regras práticas para lembrar
        // 👉 Indexed Collections = “acesso por índice numérico (organizações por oposição)
        // Fazendo app normal → usa Array
        // Mexendo com performance, gráficos, áudio, arquivos → usa TypedArray